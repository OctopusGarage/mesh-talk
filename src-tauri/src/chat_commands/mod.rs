pub(crate) fn parse_channel_id(hex_id: &str) -> Result<ConversationId, CommandError> {
    let bytes =
        hex::decode(hex_id).map_err(|_| CommandError::Validation("invalid channel id".into()))?;
    let arr: [u8; 32] = bytes
        .try_into()
        .map_err(|_| CommandError::Validation("channel id must be 32 bytes".into()))?;
    Ok(ConversationId::new(arr))
}

fn parse_event_id(hex_id: &str) -> Result<EventId, CommandError> {
    let bytes =
        hex::decode(hex_id).map_err(|_| CommandError::Validation("invalid event id".into()))?;
    let arr: [u8; 32] = bytes
        .try_into()
        .map_err(|_| CommandError::Validation("event id must be 32 bytes".into()))?;
    Ok(EventId::new(arr))
}

fn to_reaction_infos(
    views: Vec<mesh_talk_core::node::ReactionView>,
    own_account: Option<&str>,
) -> Vec<ReactionInfo> {
    views
        .into_iter()
        .map(|v| ReactionInfo {
            from_me: own_account.map(|account| v.who.iter().any(|author| author == account)),
            target: v.target,
            emoji: v.emoji,
            who: v.who,
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reaction_view(authors: &[&str]) -> mesh_talk_core::node::ReactionView {
        mesh_talk_core::node::ReactionView {
            target: "original-target".into(),
            emoji: "👍".into(),
            who: authors.iter().map(|author| (*author).to_owned()).collect(),
        }
    }

    #[test]
    fn reaction_infos_verified_account_ownership_preserves_public_principals() {
        let infos = to_reaction_infos(
            vec![reaction_view(&["external", "own-account"])],
            Some("own-account"),
        );
        assert_eq!(infos[0].from_me, Some(true));
        assert_eq!(infos[0].who, ["external", "own-account"]);
        let value = serde_json::to_value(&infos[0]).expect("reaction serializes");
        assert_eq!(value["from_me"], true);
        assert_eq!(value["who"].as_array().expect("authors").len(), 2);
    }

    #[test]
    fn reaction_infos_channel_external_ownership_is_explicitly_false() {
        let infos = to_reaction_infos(vec![reaction_view(&["external"])], Some("own-account"));
        assert_eq!(infos[0].from_me, Some(false));
        let value = serde_json::to_value(&infos[0]).expect("reaction serializes");
        assert_eq!(value["from_me"], false);
    }

    #[test]
    fn reaction_infos_adopted_unbound_physical_author_is_not_owned_by_current_account() {
        let current_account = "current-account";
        let physical_author = "linked-device-with-unbound-history";
        // A physical fallback is intentionally not an authenticated account claim.
        let infos = to_reaction_infos(
            vec![reaction_view(&[physical_author])],
            Some(current_account),
        );
        assert_eq!(
            infos[0].from_me,
            Some(false),
            "a current physical-device link cannot claim an old unbound reaction for the active account"
        );
        assert_eq!(infos[0].who, [physical_author]);
    }

    #[test]
    fn reaction_infos_dm_omits_account_ownership_and_preserves_legacy_json() {
        let infos = to_reaction_infos(vec![reaction_view(&["account-id"])], None);
        assert_eq!(infos[0].from_me, None);
        let value = serde_json::to_value(&infos[0]).expect("reaction serializes");
        assert_eq!(
            value,
            serde_json::json!({ "target": "original-target", "emoji": "👍", "who": ["account-id"] }),
        );
    }

    #[test]
    fn temp_file_keeps_real_filename_and_extension() {
        // The "send image/video" picker passes the real name: it must survive verbatim, so
        // a .mov stays a previewable .mov — NOT a MIME-derived `pasted-….quicktim`.
        let mov = "Screen Recording 2026-03-16 at 17.41.43.mov";
        assert_eq!(
            temp_file_basename("quicktime", Some(mov), 1782196051325),
            mov
        );
        // A path component is never trusted — only the basename is kept (no traversal).
        assert_eq!(
            temp_file_basename("png", Some("../../etc/passwd"), 1),
            "passwd"
        );
    }

    #[test]
    fn temp_file_synthesizes_name_for_nameless_clipboard_bytes() {
        // No real name (a pasted screenshot) → synthesize, sanitizing the ext.
        assert_eq!(temp_file_basename("png", None, 42), "pasted-42.png");
        assert_eq!(temp_file_basename("", None, 42), "pasted-42.png");
        // Degenerate names fall back to the synthetic form, not an empty/dotfile path.
        assert_eq!(temp_file_basename("png", Some(".."), 42), "pasted-42.png");
        assert_eq!(temp_file_basename("png", Some("   "), 42), "pasted-42.png");
    }

    #[test]
    fn parse_channel_id_accepts_64_hex_chars() {
        let id = parse_channel_id(&"ab".repeat(32)).expect("valid id");
        assert_eq!(id.as_bytes(), &[0xab; 32]);
    }

    #[test]
    fn parse_channel_id_rejects_wrong_length() {
        assert!(parse_channel_id(&"ab".repeat(16)).is_err()); // 16 bytes, not 32
        assert!(parse_channel_id("").is_err());
    }

    #[test]
    fn parse_channel_id_rejects_non_hex() {
        assert!(parse_channel_id(&"zz".repeat(32)).is_err()); // not hex
        assert!(parse_channel_id("abc").is_err()); // odd-length hex
    }

    #[test]
    fn parse_event_id_accepts_valid_and_rejects_bad_input() {
        assert_eq!(
            parse_event_id(&"cd".repeat(32)).expect("valid").as_bytes(),
            &[0xcd; 32]
        );
        assert!(parse_event_id(&"cd".repeat(10)).is_err()); // too short
        assert!(parse_event_id(&"gg".repeat(32)).is_err()); // not hex
    }
}
