import assert from "node:assert/strict";
import test from "node:test";
import {
  mkdtemp,
  realpath,
  mkdir,
  writeFile,
  chmod,
  symlink,
  rm,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  decodeCoreName,
  coreOutcome,
  validateExecutable,
  boundedCapture,
  limits,
} from "./linux-crash-diagnostics.mjs";

test("kernel full-path core names decode as data and reject malformed names", () => {
  assert.deepEqual(decodeCoreName("!tmp!coverage!test-bin.123.core"), {
    executable: "/tmp/coverage/test-bin",
    pid: "123",
  });
  for (const name of [
    "test.1.core",
    "!tmp!a.0.core",
    "!tmp/a.1.core",
    "!tmp!a.1.core/extra",
    "!tmp!a.1.core\0",
  ])
    assert.throws(() => decodeCoreName(name));
  assert.equal(
    decodeCoreName("!tmp!$(echo bad).12.core").executable,
    "/tmp/$(echo bad)",
  );
});
test("bounded capture retains exact prefix and reports truncation", () => {
  const capture = boundedCapture(4);
  capture.append(Buffer.from("ab"));
  capture.append(Buffer.from("cdef"));
  capture.append(Buffer.from("g"));
  assert.deepEqual(capture.result(), { output: "abcd", truncated: true });
  assert.equal(limits.cores, 8);
  assert.equal(limits.totalMs, 120000);
  assert.equal(limits.imageBytes, 2 * 1024 ** 3);
});
test(
  "core executables must resolve to regular executable files inside exact coverage owner",
  {
    skip:
      process.platform === "win32"
        ? "Linux kernel paths and POSIX executable modes; actual kernel control runs on Linux"
        : false,
  },
  async (t) => {
    const root = await mkdtemp(join(tmpdir(), "mesh-core-path-"));
    t.after(() => rm(root, { recursive: true, force: true }));
    const owner = join(root, "target/llvm-cov-target/debug/deps");
    await mkdir(owner, { recursive: true });
    const executable = join(owner, "host-bin");
    await writeFile(executable, "fixture");
    await chmod(executable, 0o700);
    const name = (path) => `${path.replaceAll("/", "!")}.123.core`;
    assert.equal(
      (await validateExecutable(name(executable), root)).executable,
      await realpath(executable),
    );
    const outside = join(root, "outside");
    await writeFile(outside, "outside");
    await chmod(outside, 0o700);
    await assert.rejects(validateExecutable(name(outside), root), /outside/u);
    const link = join(owner, "link");
    await symlink(outside, link);
    await assert.rejects(validateExecutable(name(link), root), /outside/u);
    await chmod(executable, 0o600);
    await assert.rejects(
      validateExecutable(name(executable), root),
      /outside/u,
    );
    await assert.rejects(validateExecutable(name(owner), root), /outside/u);
  },
);

// GDB can exit zero after declining a core; only actual crash frames qualify.
test("core qualification rejects zero-exit empty, mismatched and truncated evidence", () => {
  const output =
    "Core was generated by `host --exact test'.\nProgram terminated with signal SIGSEGV, Segmentation fault.\n#0  crash ()\n";
  assert.equal(coreOutcome({ output }), "symbolized");
  assert.equal(
    coreOutcome({ output: "Reading symbols..." }),
    "core-unconfirmed",
  );
  assert.equal(
    coreOutcome({ output: output.replace("#0", "#1") }),
    "core-unconfirmed",
  );
  assert.equal(
    coreOutcome({
      output:
        output + "warning: core file may not match specified executable file.",
    }),
    "core-mismatch",
  );
  assert.equal(
    coreOutcome({ output: output + "warning: core file may be truncated" }),
    "core-truncated",
  );
  assert.equal(coreOutcome({ output }, true), "core-truncated");
  assert.equal(coreOutcome({ output, truncated: true }), "text-truncated");
});
