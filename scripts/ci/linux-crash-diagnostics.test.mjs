test("kernel full-path core names decode as data and reject malformed names", () => {
  assert.deepEqual(decodeCoreName("!tmp!coverage!test-bin.123.core"), {
    executable: "/tmp/coverage/test-bin",
    pid: "123",
  });
  for (const name of [
    "test.1.core",
    "!tmp!a.0.core",
    "!tmp/a.1.core",
    "!tmp!a.1.core/extra",
    "!tmp!a.1.core\0",
  ])
    assert.throws(() => decodeCoreName(name));
  assert.equal(
    decodeCoreName("!tmp!$(echo bad).12.core").executable,
    "/tmp/$(echo bad)",
  );
});
test("bounded capture retains exact prefix and reports truncation", () => {
  const capture = boundedCapture(4);
  capture.append(Buffer.from("ab"));
  capture.append(Buffer.from("cdef"));
  capture.append(Buffer.from("g"));
  assert.deepEqual(capture.result(), { output: "abcd", truncated: true });
  assert.equal(limits.cores, 8);
  assert.equal(limits.totalMs, 120000);
  assert.equal(limits.imageBytes, 2 * 1024 ** 3);
});
test(
  "core executables must resolve to regular executable files inside exact coverage owner",
  {
    skip:
      process.platform === "win32"
        ? "Linux kernel paths and POSIX executable modes; actual kernel control runs on Linux"
        : false,
  },
  async (t) => {
    const root = await mkdtemp(join(tmpdir(), "mesh-core-path-"));
    t.after(() => rm(root, { recursive: true, force: true }));
    const owner = join(root, "target/llvm-cov-target/debug/deps");
    await mkdir(owner, { recursive: true });
    const executable = join(owner, "host-bin");
    await writeFile(executable, "fixture");
    await chmod(executable, 0o700);
    const name = (path) => `${path.replaceAll("/", "!")}.123.core`;
    assert.equal(
      (await validateExecutable(name(executable), root)).executable,
      await realpath(executable),
    );
    const outside = join(root, "outside");
    await writeFile(outside, "outside");
    await chmod(outside, 0o700);
    await assert.rejects(validateExecutable(name(outside), root), /outside/u);
    const link = join(owner, "link");
    await symlink(outside, link);
    await assert.rejects(validateExecutable(name(link), root), /outside/u);
    await chmod(executable, 0o600);
    await assert.rejects(
      validateExecutable(name(executable), root),
      /outside/u,
    );
    await assert.rejects(validateExecutable(name(owner), root), /outside/u);
  },
);

// GDB can exit zero after declining a core; only actual crash frames qualify.
test("core qualification rejects zero-exit empty, mismatched and truncated evidence", () => {
  const output =
    "Core was generated by `host --exact test'.\nProgram terminated with signal SIGSEGV, Segmentation fault.\n#0  crash ()\n";
  assert.equal(coreOutcome({ output }), "symbolized");
  assert.equal(
    coreOutcome({ output: "Reading symbols..." }),
    "core-unconfirmed",
  );
  assert.equal(
    coreOutcome({ output: output.replace("#0", "#1") }),
    "core-unconfirmed",
  );
  assert.equal(
    coreOutcome({
      output:
        output + "warning: core file may not match specified executable file.",
    }),
    "core-mismatch",
  );
  assert.equal(
    coreOutcome({ output: output + "warning: core file may be truncated" }),
    "core-truncated",
  );
  assert.equal(coreOutcome({ output }, true), "core-truncated");
  assert.equal(coreOutcome({ output, truncated: true }), "text-truncated");
});

test(
  "recovery state publishes atomically and rejected writes retain canonical authority",
  { timeout: 10_000 },
  async (t) => {
    const root = await mkdtemp(join(tmpdir(), "mesh-core-state-"));
    t.after(() => rm(root, { recursive: true, force: true }));
    const p = { state: join(root, "state.json") };
    const old = {
      mounted: true,
      patternChanged: true,
      originalPattern: "original",
    };
    const next = { ...old, mounted: false };
    await writeFile(p.state, JSON.stringify(old));
    let entered;
    let release;
    const enteredWrite = new Promise((resolve) => {
      entered = resolve;
    });
    const writeReleased = new Promise((resolve) => {
      release = resolve;
    });
    const publishing = save(p, next, {
      async write(path, data) {
        await writeFile(path, data);
        entered();
        await writeReleased;
      },
    });
    try {
      await Promise.race([enteredWrite, publishing]);
      assert.deepEqual(
        JSON.parse(await readFile(p.state, "utf8")),
        old,
        "candidate bytes must not replace recovery authority before completed publication",
      );
    } finally {
      release();
      await publishing;
    }
    assert.deepEqual(JSON.parse(await readFile(p.state, "utf8")), next);
    assert.deepEqual(await readdir(root), ["state.json"]);
    await assert.rejects(
      save(p, old, {
        async write(path, data) {
          await writeFile(path, data);
          throw Error("controlled write rejection");
        },
      }),
      /controlled write rejection/u,
    );
    assert.deepEqual(JSON.parse(await readFile(p.state, "utf8")), next);
    assert.deepEqual(
      await readdir(root),
      ["state.json"],
      "rejected candidate is removed",
    );
  },
);

test("selftest fixture retires only its owned tree on success and failure", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "mesh-core-selftest-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const state = { workspace: join(root, "workspace") };
  const p = { root: join(root, "diagnostics") };
  await mkdir(state.workspace);
  await mkdir(p.root);
  const target = join(state.workspace, "target");
  const coverage = join(target, "llvm-cov-target");
  const exercise = async (fail = false, concurrentFile = false) => {
    const operation = withSelftestFiles(
      p,
      state,
      async ({ source, executable }) => {
        assert.match(await readFile(source, "utf8"), /diagnostic_exit_crash/u);
        await writeFile(executable, "owned fixture executable");
        if (concurrentFile)
          await writeFile(join(coverage, "unrelated"), "preserve");
        if (fail) throw Error("controlled compile failure");
        return "completed";
      },
    );
    if (fail) await assert.rejects(operation, /controlled compile failure/u);
    else assert.equal(await operation, "completed");
    assert.deepEqual(await readdir(p.root), [], "source must retire");
  };
  for (const fail of [false, true]) {
    await exercise(fail);
    assert.deepEqual(
      await readdir(state.workspace),
      [],
      "fresh consumer must retain no target, even empty",
    );
    await mkdir(target);
    await writeFile(join(target, "native-output"), "preserve");
    await exercise(fail);
    assert.deepEqual(await readdir(target), ["native-output"]);
    assert.equal(
      await readFile(join(target, "native-output"), "utf8"),
      "preserve",
    );
    await rm(target, { recursive: true });
    await mkdir(join(coverage, "debug/deps"), { recursive: true });
    await writeFile(
      join(coverage, "debug/deps/linux-exit-crash-control"),
      "pre-existing executable",
    );
    await exercise(fail);
    assert.equal(
      await readFile(
        join(coverage, "debug/deps/linux-exit-crash-control"),
        "utf8",
      ),
      "pre-existing executable",
    );
    await rm(target, { recursive: true });
  }
  await assert.rejects(
    withSelftestFiles({ root: join(root, "missing-diagnostics") }, state, () =>
      assert.fail("source setup failure must prevent execution"),
    ),
    { code: "ENOENT" },
  );
  assert.deepEqual(
    await readdir(state.workspace),
    [],
    "partial setup must retire created directories",
  );
  await exercise(true, true);
  assert.deepEqual(
    await readdir(coverage),
    ["unrelated"],
    "new unrelated contents prevent ancestor removal",
  );
  assert.equal(await readFile(join(coverage, "unrelated"), "utf8"), "preserve");
});
